def _compute_profile_metrics(records: List[Dict[str, Any]], scenario_counts: Dict[str, int]) -> Dict[str, Any]:
    total_records = len(records)
    features: Dict[str, List[float]] = {
        "temperature_C": [],
        "humidity_pct": [],
        "PM1_0": [],
        "PM2_5": [],
        "PM10": [],
        "MQ2_V": [],
        "MQ9_V": [],
        "MQ135_V": [],
        "coarse_ratio": [],
        "fine_ratio": [],
    }
    missing_counts = {k: 0 for k in features}
    pm_violations = 0

    for r in records:
        env = r.get("environment", {})
        pm = r.get("particulate_matter", {})
        gas = r.get("gas_sensors", {})

        t = env.get("temperature_C")
        h = env.get("humidity_pct")
        pm1 = pm.get("PM1_0")
        pm25 = pm.get("PM2_5")
        pm10 = pm.get("PM10")
        mq2 = gas.get("MQ2", {}).get("voltage_V")
        mq9 = gas.get("MQ9", {}).get("voltage_V")
        mq135 = gas.get("MQ135", {}).get("voltage_V")

        for val, name in [
            (t, "temperature_C"),
            (h, "humidity_pct"),
            (pm1, "PM1_0"),
            (pm25, "PM2_5"),
            (pm10, "PM10"),
            (mq2, "MQ2_V"),
            (mq9, "MQ9_V"),
            (mq135, "MQ135_V"),
        ]:
            if val is None:
                missing_counts[name] += 1
            else:
                features[name].append(val)

        if pm1 is not None and pm25 is not None and pm10 is not None:
            if not (pm1 <= pm25 + 0.5 <= pm10 + 1.0):
                pm_violations += 1
            if pm1 > 0:
                features["fine_ratio"].append(pm25 / pm1)
            if pm25 > 0:
                features["coarse_ratio"].append(pm10 / pm25)

    stats: Dict[str, Any] = {}
    for name, vals in features.items():
        arr = np.array(vals)
        stats[name] = {
            "count": len(arr),
            "missing_pct": round((missing_counts.get(name, 0) / max(1, total_records)) * 100.0, 2),
            "min": round(float(np.min(arr)), 2) if len(arr) else None,
            "max": round(float(np.max(arr)), 2) if len(arr) else None,
            "mean": round(float(np.mean(arr)), 2) if len(arr) else None,
            "std": round(float(np.std(arr)), 2) if len(arr) else None,
            "median": round(float(np.median(arr)), 2) if len(arr) else None,
            "q25": round(float(np.percentile(arr, 25)), 2) if len(arr) else None,
            "q75": round(float(np.percentile(arr, 75)), 2) if len(arr) else None,
        }

    corr_keys = ["temperature_C", "humidity_pct", "PM2_5", "PM10", "MQ2_V", "MQ9_V", "MQ135_V"]
    corr_data = np.column_stack([features[k][:total_records] for k in corr_keys])
    corr_matrix = np.corrcoef(corr_data, rowvar=False)

    correlations: Dict[str, Dict[str, float]] = {}
    for i, k1 in enumerate(corr_keys):
        correlations[k1] = {}
        for j, k2 in enumerate(corr_keys):
            correlations[k1][k2] = round(float(corr_matrix[i, j]), 3)

    return {
        "total_records": total_records,
        "scenario_counts": scenario_counts,
        "stats": stats,
        "pm_violations": pm_violations,
        "correlations": correlations,
    }


def profile_datasets(samples_per_scenario: int = 100) -> Dict[str, Any]:
    """Profile data generated by the improved SensorSimulator."""
    records: List[Dict[str, Any]] = []
    scenario_counts: Dict[str, int] = {}
    start = datetime(2026, 9, 1, 0, 0, 0, tzinfo=timezone.utc)

    for scenario in SCENARIO_PROFILES:
        sim = SensorSimulator(
            scenario=scenario,
            node_id=f"profile-{scenario}",
            seed=42,
            start_time=start,
            sampling_interval_seconds=300,
        )
        scenario_counts[scenario] = 0
        for _ in range(samples_per_scenario):
            r = sim.generate()
            r["_scenario"] = scenario
            records.append(r)
            scenario_counts[scenario] += 1

    return _compute_profile_metrics(records, scenario_counts)


def profile_baseline_datasets(samples_per_scenario: int = 100) -> Dict[str, Any]:
    """Profile data generated by the legacy pre-audit baseline formulas (commit 791253a)."""
    import random
    rng = random.Random(42)
    records: List[Dict[str, Any]] = []
    scenario_counts: Dict[str, int] = {}

    for scenario, profile in SCENARIO_PROFILES.items():
        scenario_counts[scenario] = samples_per_scenario
        pm25, pm10, mq2, mq9, mq135, temp, hum = profile
        for _ in range(samples_per_scenario):
            def r(t):
                noise = rng.uniform(-0.02, 0.02)
                return rng.uniform(t[0], t[1]) * (1 + noise)

            v_pm25 = r(pm25)
            v_pm10 = r(pm10)
            if v_pm10 < v_pm25:
                v_pm10 = v_pm25 + rng.uniform(1, 5)
            # Legacy fixed assumption: PM1.0 = 0.5 * PM2.5
            v_pm1_0 = v_pm25 * 0.5

            v_mq2 = r(mq2)
            v_mq9 = r(mq9)
            v_mq135 = r(mq135)
            v_temp = r(temp)
            v_hum = r(hum)

            record = {
                "environment": {"temperature_C": round(v_temp, 2), "humidity_pct": round(v_hum, 2)},
                "particulate_matter": {"PM1_0": round(v_pm1_0, 2), "PM2_5": round(v_pm25, 2), "PM10": round(v_pm10, 2)},
                "gas_sensors": {
                    "MQ2": {"voltage_V": round(max(0.0, min(5.0, v_mq2)), 3), "raw_adc": int(round((v_mq2 / 5.0) * 1023))},
                    "MQ9": {"voltage_V": round(max(0.0, min(5.0, v_mq9)), 3), "raw_adc": int(round((v_mq9 / 5.0) * 1023))},
                    "MQ135": {"voltage_V": round(max(0.0, min(5.0, v_mq135)), 3), "raw_adc": int(round((v_mq135 / 5.0) * 1023))},
                },
                "_scenario": scenario,
            }
            records.append(record)

    return _compute_profile_metrics(records, scenario_counts)


def format_profile_table(profile: Dict[str, Any], title: str = "NAVOSEDGE SYNTHETIC DATA PROFILE") -> str:
    lines: List[str] = []
    lines.append("=" * 76)
    lines.append(f"{title} (N = {profile['total_records']} samples)")
    lines.append("=" * 76)
    lines.append("\nScenario Coverage:")
    for sc, count in profile["scenario_counts"].items():
        lines.append(f"  {sc:22}: {count} records")

    lines.append(f"\nParticulate Physical Constraint Violations (PM1 <= PM2.5 <= PM10): {profile['pm_violations']}")
    lines.append("\nFeature Distribution Summary:")
    lines.append(f"{'Feature':<16} | {'Min':>6} | {'Max':>6} | {'Mean':>7} | {'Std':>6} | {'Median':>6} | {'IQR':>6} | {'Missing%':>8}")
    lines.append("-" * 76)
    for feat, s in profile["stats"].items():
        iqr = round(s["q75"] - s["q25"], 2) if s["q75"] is not None and s["q25"] is not None else 0.0
        lines.append(f"{feat:<16} | {s['min']:>6} | {s['max']:>6} | {s['mean']:>7} | {s['std']:>6} | {s['median']:>6} | {iqr:>6} | {s['missing_pct']:>7}%")

    lines.append("\nKey Feature Correlation Matrix:")
    corr_keys = ["temperature_C", "humidity_pct", "PM2_5", "PM10", "MQ2_V", "MQ9_V", "MQ135_V"]
    header = f"{'':<14}" + "".join(f"{k[:7]:>8}" for k in corr_keys)
    lines.append(header)
    lines.append("-" * len(header))
    for k1 in corr_keys:
        row = f"{k1:<14}" + "".join(f"{profile['correlations'][k1][k2]:>8.2f}" for k2 in corr_keys)
        lines.append(row)

    return "\n".join(lines)


def format_comparison_table(before: Dict[str, Any], after: Dict[str, Any]) -> str:
    lines: List[str] = []
    lines.append("=" * 88)
    lines.append("NAVOSEDGE SYNTHETIC DATA PROFILE: BEFORE vs AFTER COMPARISON")
    lines.append("=" * 88)
    lines.append(f"{'Feature':<16} | {'Before Mean':>11} | {'After Mean':>11} | {'Before Std':>10} | {'After Std':>10} | {'Before [Min,Max]':>16} | {'After [Min,Max]':>16}")
    lines.append("-" * 88)
    for feat in after["stats"]:
        b = before["stats"].get(feat, {})
        a = after["stats"].get(feat, {})
        b_range = f"[{b.get('min', '-')},{b.get('max', '-')}]"
        a_range = f"[{a.get('min', '-')},{a.get('max', '-')}]"
        lines.append(
            f"{feat:<16} | {b.get('mean', 0.0):>11.2f} | {a.get('mean', 0.0):>11.2f} | "
            f"{b.get('std', 0.0):>10.2f} | {a.get('std', 0.0):>10.2f} | "
            f"{b_range:>16} | {a_range:>16}"
        )

    lines.append("\nPhysical Realism Metrics:")
    b_fine = before["stats"]["fine_ratio"]
    a_fine = after["stats"]["fine_ratio"]
    lines.append(f"  PM2.5 / PM1.0 (Fine Ratio):")
    lines.append(f"    - Baseline: Constant {b_fine['mean']:.2f} (Std: {b_fine['std']:.2f}, Min: {b_fine['min']}, Max: {b_fine['max']}) [Fixed 0.5 rule]")
    lines.append(f"    - Phase 1:  Mean {a_fine['mean']:.2f} (Std: {a_fine['std']:.2f}, Min: {a_fine['min']:.2f}, Max: {a_fine['max']:.2f}) [Scenario-driven dynamic aerosol distribution]")
    lines.append(f"\n  Temperature / Humidity Diurnal Correlation:")
    lines.append(f"    - Baseline: r = {before['correlations']['temperature_C']['humidity_pct']:.2f} (Independent uniform random noise)")
    lines.append(f"    - Phase 1:  r = {after['correlations']['temperature_C']['humidity_pct']:.2f} (Realistic diurnal cycle with synoptic weather waves)")
    lines.append(f"\n  Temperature / MQ2 Voltage Cross-Sensitivity Correlation:")
    lines.append(f"    - Baseline: r = {before['correlations']['temperature_C']['MQ2_V']:.2f} (No environmental cross-sensitivity)")
    lines.append(f"    - Phase 1:  r = {after['correlations']['temperature_C']['MQ2_V']:.2f} (MOS temperature/humidity surface resistance shifts)")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="NavosEdge Synthetic Data Profiler")
    parser.add_argument("--samples", type=int, default=100, help="Samples per scenario (default: 100)")
    parser.add_argument("--baseline", action="store_true", help="Profile legacy baseline rather than improved simulator")
    parser.add_argument("--compare", action="store_true", help="Run before/after comparison between legacy baseline and improved simulator")
    parser.add_argument("--json", action="store_true", help="Output raw JSON data")
    parser.add_argument("--output", type=Path, help="Save report to file")
    args = parser.parse_args()

    if args.compare:
        before = profile_baseline_datasets(args.samples)
        after = profile_datasets(args.samples)
        if args.json:
            result = json.dumps({"baseline": before, "phase1_improved": after}, indent=2)
        else:
            result = format_comparison_table(before, after)
    elif args.baseline:
        profile = profile_baseline_datasets(args.samples)
        if args.json:
            result = json.dumps(profile, indent=2)
        else:
            result = format_profile_table(profile, "NAVOSEDGE SYNTHETIC DATA PROFILE (LEGACY BASELINE)")
    else:
        profile = profile_datasets(args.samples)
        if args.json:
            result = json.dumps(profile, indent=2)
        else:
            result = format_profile_table(profile, "NAVOSEDGE SYNTHETIC DATA PROFILE (PHASE 1 IMPROVED)")

    print(result)

    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(result, encoding="utf-8")
        print(f"\nSaved profile output to: {args.output}")


if __name__ == "__main__":
    main()
